const parser = new DOMParser();

function buildSvg(name, className) {
    const body = ICONS[name];
    if (!body) return null;
    const markup = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" `
        + `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" `
        + `class="${className}" aria-hidden="true">${body}</svg>`;
    // Parse in the SVG namespace so the child shapes are real SVG nodes
    // regardless of browser innerHTML-on-SVG support.
    const doc = parser.parseFromString(markup, 'image/svg+xml');
    return doc.documentElement.tagName === 'svg' ? doc.documentElement : null;
}

// Swap every not-yet-processed [data-lucide] element under `root` for an
// <svg>. Idempotent: processed nodes are replaced outright so a second call
// is a no-op over the same subtree.
export function createIcons(root = document) {
    root.querySelectorAll('[data-lucide]').forEach(el => {
        const svg = buildSvg(el.getAttribute('data-lucide'), el.getAttribute('class') || '');
        if (svg) el.replaceWith(document.importNode(svg, true));
    });
}

// A ready-to-insert SVG markup string (for template-literal HTML that is
// assigned via innerHTML and then had lucide.createIcons() run over it —
// callers that build strings can keep doing that and call createIcons()
// after insertion, exactly as before).
export function iconMarkup(name, className = '') {
    const body = ICONS[name] || '';
    return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" `
        + `stroke-linecap="round" stroke-linejoin="round" class="${className}" aria-hidden="true">${body}</svg>`;
}
