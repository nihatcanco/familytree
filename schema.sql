-- PostgreSQL schema for the family tree app.
--
-- server.py runs this on every startup (ensure_schema()), so every statement is
-- IF NOT EXISTS / idempotent. The one-time data load from the old data.sqlite is
-- migrate_sqlite_to_pg.py.
--
-- Identifiers are all lowercase: PostgreSQL folds unquoted names to lowercase,
-- so the old camelCase columns (passwordHash, spouse1Id, ...) become
-- passwordhash, spouse1id, ... -- server.py reads them at that spelling.
--
-- id columns:
--   people / spouses / parents  -- plain integer PK; server.py's _next_id()
--     (SELECT MAX(id)+1, serialised on a process-wide write lock) assigns them,
--     carried over from the original MySQL-style "id INT AUTO_INCREMENT" DDL.
--   roots / rootmembers / users -- real IDENTITY columns; their inserts use
--     RETURNING id.

CREATE TABLE IF NOT EXISTS people (
    id          integer PRIMARY KEY,
    name        text NOT NULL,
    surname     text,
    gender      integer DEFAULT 0,   -- 0: unknown, 1: male, 2: female
    birthdate   text,                -- kept as text: values from SQLite are free-form / partial
    birthplace  text,
    note        text,
    dateofdeath text
);

CREATE TABLE IF NOT EXISTS spouses (
    id        integer PRIMARY KEY,
    spouse1id integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    spouse2id integer NOT NULL REFERENCES people(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS parents (
    id        integer PRIMARY KEY,
    childid   integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    parent1id integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    parent2id integer          REFERENCES people(id) ON DELETE CASCADE
);

-- A root is a standalone family-origin marker (a diamond in the UI): an editable
-- title and an integer generation that every descendant generation counts from.
CREATE TABLE IF NOT EXISTS roots (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      text NOT NULL DEFAULT 'ROOT',
    generation integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS rootmembers (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rootid   integer NOT NULL REFERENCES roots(id) ON DELETE CASCADE,
    personid integer NOT NULL UNIQUE REFERENCES people(id) ON DELETE CASCADE
);

-- Login accounts. personid links an account to "who they are" in the tree; it is
-- informational only and nullable (not every account maps to a person).
CREATE TABLE IF NOT EXISTS users (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     text NOT NULL,
    passwordhash text NOT NULL,
    role         text NOT NULL DEFAULT 'viewer',
    personid     integer REFERENCES people(id) ON DELETE SET NULL,
    createdat    timestamptz NOT NULL DEFAULT now()
);

-- Case-insensitive uniqueness on username (replaces SQLite's COLLATE NOCASE).
-- server.py matches with lower(username) = lower(%s).
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username));

CREATE TABLE IF NOT EXISTS sessions (
    token     text PRIMARY KEY,
    userid    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    createdat timestamptz NOT NULL DEFAULT now(),
    expiresat timestamptz NOT NULL
);
